function translateValue(value: string): string {
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  const core = value.slice(leading.length, value.length - trailing.length || undefined);
  if (!core) return value;

  const direct = TRANSLATIONS[core];
  if (direct) return `${leading}${direct}${trailing}`;

  for (const [pattern, replacement] of PATTERNS) {
    const match = pattern.exec(core);
    if (match) {
      const translated = typeof replacement === "function" ? replacement(match) : core.replace(pattern, replacement);
      return `${leading}${translated}${trailing}`;
    }
  }

  return value;
}

const TRANSLATABLE_ATTRIBUTES = ["title", "aria-label", "aria-description", "placeholder", "alt"];
const IGNORED_TAGS = new Set(["SCRIPT", "STYLE", "PRE", "CODE", "TEXTAREA"]);

function shouldIgnoreText(node: Text): boolean {
  const parent = node.parentElement;
  return !parent || Boolean(parent.closest("[data-no-translate], script, style, pre, code, textarea"));
}

function translateElement(element: Element): void {
  for (const attribute of TRANSLATABLE_ATTRIBUTES) {
    const current = element.getAttribute(attribute);
    if (current) {
      const translated = translateValue(current);
      if (translated !== current) element.setAttribute(attribute, translated);
    }
  }

  if (IGNORED_TAGS.has(element.tagName)) return;
  for (const child of Array.from(element.childNodes)) {
    if (child.nodeType === Node.TEXT_NODE) {
      const text = child as Text;
      if (!shouldIgnoreText(text)) {
        const translated = translateValue(text.nodeValue ?? "");
        if (translated !== text.nodeValue) text.nodeValue = translated;
      }
    } else if (child.nodeType === Node.ELEMENT_NODE) {
      translateElement(child as Element);
    }
  }
}

/** Mount the fixed Simplified Chinese locale over every app window. */
export function ChineseLocale({ children }: { children: ReactNode }) {
  useEffect(() => {
    document.documentElement.lang = "zh-CN";
    const root = document.getElementById("root");
    if (!root) return;

    let scheduled = false;
    const translate = () => {
      scheduled = false;
      translateElement(root);
    };
    const schedule = () => {
      if (scheduled) return;
      scheduled = true;
      queueMicrotask(translate);
    };

    translate();
    const observer = new MutationObserver(schedule);
    observer.observe(root, {
      subtree: true,
      childList: true,
      characterData: true,
      attributes: true,
      attributeFilter: TRANSLATABLE_ATTRIBUTES,
    });
    return () => observer.disconnect();
  }, []);

  return <>{children}</>;
}

